"""ARM X, stage 4: render results/xs/armx_scores.json as results/xs/ARMX_REPORT.md.
Every number in the report is printed from the JSON; nothing here is typed."""
import json, pathlib
import numpy as np
from scipy.stats import spearmanr

ROOT = pathlib.Path(__file__).resolve().parents[1]
S = json.load(open(ROOT / "results" / "xs" / "armx_scores.json"))
V, SEG = S["verdict"], S["segments"]
PRIM = ["p0841_w00", "p0841_ag144", "p0841_ag174", "p0500p2a"]
NAMES = {"c1_p0139_w016": "PHerc0139 w016 (C1, in distribution)", "p0841_w00": "PHerc0841 w00",
         "p0841_ag144": "PHerc0841 ag144", "p0841_ag174": "PHerc0841 ag174", "p0500p2a": "PHerc0500P2 500p2a",
         "man5_outer3": "MAN5 outer_3 (exploratory)", "p0009b": "PHerc0009B (exploratory)", "p0500p2_m1": "PHerc0500P2 -1 (exploratory)"}
f4 = lambda x: "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.4f}"
L = ["# ARM X: does ink_9um transfer to scrolls it never trained on?", "",
     "Generated by `ops/xs_report.py` from `results/xs/armx_scores.json`. Pre-registration: "
     "PREREGISTRATION.md, amendment 2026-09-22 23:3x.", "",
     "## Gate and verdict, as pre-registered", "",
     f"- C1, primary checkpoint on pherc0139-w016 validation pixels: **{f4(V['C1_auc_chosen_direction'])}** "
     f"({V['C1_direction']}), bar 0.85: **{'PASS' if V['C1_pass'] else 'FAIL'}**",
     f"- Diagnostic added after that failure: seed43 step-060000, same pipeline, same pixels: "
     f"**{f4(V.get('C1_diagnostic_seed43_step060000_forward'))}** (kadenpool, villa #1845: 0.912)",
     f"- Verdict: **{V['verdict']}**", ""]
if "primary_median" in V:
    L.append(f"- Primary median over the four held-out segments: **{f4(V['primary_median'])}**")
L += ["", "## Primary checkpoint (seed42 step-075000), every segment", "",
      "| segment | ink rate | forward | reverse | label-free pick | AUC picked | 95% block CI |", "|---|---|---|---|---|---|---|"]
for s, r in SEG.items():
    p = r["rows"].get("hybrid_3d2d-seed42_step-075000", {})
    if not p: continue
    ch = p.get("chosen"); ci = p.get(ch, {}).get("ci95") if ch else None
    L.append(f"| {NAMES.get(s, s)} | {r['ink_rate']:.3f} | {f4(p.get('forward', {}).get('auc'))} | {f4(p.get('reverse', {}).get('auc'))} "
             f"| {ch} | **{f4(p.get('auc_chosen'))}** | {'n/a' if not ci else f'{ci[0]:.3f} to {ci[1]:.3f}'} |")
ck = sorted({k for r in SEG.values() for k in r["rows"]})
L += ["", "## Every checkpoint: in distribution against held out", "",
      "| checkpoint | C1, in distribution | median over held-out primary segments | label-free pick = better direction |", "|---|---|---|---|"]
xin, xout = [], []
for k in ck:
    c1 = SEG.get("c1_p0139_w016", {}).get("rows", {}).get(k, {}).get("auc_chosen", float("nan"))
    held = [SEG[s]["rows"][k]["auc_chosen"] for s in PRIM if s in SEG and k in SEG[s]["rows"] and "auc_chosen" in SEG[s]["rows"][k]]
    hits = [SEG[s]["rows"][k]["auc_chosen"] == SEG[s]["rows"][k]["auc_oracle"] for s in SEG if k in SEG[s]["rows"] and "auc_chosen" in SEG[s]["rows"][k]]
    med = float(np.median(held)) if len(held) == len(PRIM) else float("nan")
    if not np.isnan(c1) and not np.isnan(med) and not k.startswith("ensemble"): xin.append(c1); xout.append(med)  # checkpoints only
    L.append(f"| {k.replace('hybrid_3d2d-', '')} | {f4(c1)} | {f4(med)} ({len(held)} of {len(PRIM)}) | {sum(hits)} of {len(hits)} |")
if len(xin) >= 5:
    rho, pv = spearmanr(xin, xout)
    L += ["", f"Across {len(xin)} checkpoints, Spearman between in-distribution and held-out AUC: **{rho:.3f}** (p = {pv:.3g})."]
P841 = ["p0841_w00", "p0841_ag144", "p0841_ag174"]
ALLS = ["c1_p0139_w016"] + PRIM
L += ["", "## Every checkpoint on every segment, direction chosen without labels", "",
      "| checkpoint | " + " | ".join(NAMES[s].split(" (")[0] for s in ALLS) + " |", "|---|" + "---|" * len(ALLS)]
for k in ck:
    L.append(f"| {k.replace('hybrid_3d2d-', '')} | " + " | ".join(f4(SEG.get(s, {}).get("rows", {}).get(k, {}).get("auc_chosen")) for s in ALLS) + " |")
x8 = [(SEG["c1_p0139_w016"]["rows"][k]["auc_chosen"], float(np.median([SEG[s]["rows"][k]["auc_chosen"] for s in P841])))
      for k in ck if k.startswith("hybrid") and all(k in SEG.get(s, {}).get("rows", {}) for s in P841 + ["c1_p0139_w016"])]
if len(x8) >= 5:
    r8, p8 = spearmanr([a for a, _ in x8], [b for _, b in x8])
    L += ["", f"Across {len(x8)} checkpoints, Spearman between in-distribution AUC and the PHerc0841 median: **{r8:.3f}** (p = {p8:.3g})."]
L += ["", "## Per source: PHerc0841 (a scroll, three segments) and PHerc0500P2 500p2a (a detached fragment)", "",
      "| checkpoint | PHerc0841 median | PHerc0500P2 500p2a |", "|---|---|---|"]
for k in ck:
    m8 = [SEG[s]["rows"][k]["auc_chosen"] for s in P841 if s in SEG and k in SEG[s]["rows"] and "auc_chosen" in SEG[s]["rows"][k]]
    a5 = SEG.get("p0500p2a", {}).get("rows", {}).get(k, {}).get("auc_chosen", float("nan"))
    L.append(f"| {k.replace('hybrid_3d2d-', '')} | {f4(float(np.median(m8))) if len(m8) == 3 else 'n/a'} | {f4(a5)} |")
pf = ROOT / "results" / "xs" / "depth_profiles.json"
if pf.exists():
    PR = json.loads(pf.read_text())
    L += ["", "Mean CT intensity across the pooled planes (every 8th supported pixel, `results/xs/depth_profiles.json`): "
          + "; ".join(f"{NAMES.get(k, k)} {min(v):.1f} to {max(v):.1f}" for k, v in PR.items() if k in SEG) + ". "
          f"The fragment's intensity falls to {min(PR['p0500p2a']):.1f} on one side of its window, consistent with an exposed surface; "
          f"the PHerc0841 renders stay at or above {min(min(PR[k]) for k in P841 if k in PR):.1f}."]
dc = sorted((ROOT / "results" / "xs" / "depthcheck").glob("*.json"))
if dc:
    L += ["", "## Exploratory, not pre-registered: is held-out AUC depressed by window placement?", "",
          "The 17-plane window shifted by k pooled planes, in the direction the label-free rule picked, primary checkpoint.", "",
          "| segment | direction | k = -4 | k = -2 | k = 0 | k = +2 | k = +4 |", "|---|---|---|---|---|---|---|"]
    for f in dc:
        j = json.loads(f.read_text()); a_ = j["auc_by_shift"]
        if len(a_) < 2: continue
        L.append(f"| {NAMES.get(j['segment'], j['segment'])} | {j['direction']} | " + " | ".join(f4(a_.get(str(k))) for k in (-4, -2, 0, 2, 4)) + " |")
pairs = [(s, k) for s in SEG for k in SEG[s]["rows"] if k.startswith("hybrid") and SEG[s]["rows"][k].get("chosen")]
if pairs:
    EXPL = {s for s, n in NAMES.items() if "(exploratory)" in n}
    kept = lambda ps: sum(SEG[s]["rows"][k]["auc_chosen"] == SEG[s]["rows"][k]["auc_oracle"] for s, k in ps)
    pre = [(s, k) for s, k in pairs if s not in EXPL]; ex = len(pairs) - len(pre)
    gap = max(abs(SEG[s]["rows"][k]["forward"]["auc"] - SEG[s]["rows"][k]["reverse"]["auc"]) for s, k in pairs if s in PRIM)
    both = f" ({kept(pairs)} of {len(pairs)} including the {len({s for s, _ in pairs} & EXPL)} exploratory segments)" if ex else ""
    L += ["", f"Direction: over the pre-registered segments the label-free rule kept the better direction in {kept(pre)} of {len(pre)} (segment, checkpoint) cases{both}; "
          f"the largest forward-reverse gap on a held-out segment is {gap:.4f}."]
    jj = [json.loads(f.read_text()) for f in dc]; jj = [j for j in jj if len(j["auc_by_shift"]) >= 2]
    if jj:
        L += [f"Window placement: the largest gain from any shift in the exploratory check is {max(max(j['auc_by_shift'].values()) - j['auc_by_shift']['0'] for j in jj):.4f}."]
L += ["", "## Controls", "",
      f"- C2 block-shuffle floor, pre-registered bar every seed within 0.03 of 0.5: **{'PASS' if V['C2_pass'] else 'FAIL'}** "
      f"(worst deviation {f4(V['C2_worst_abs_dev'])})"]
for s, c in V.get("C2_per_segment", {}).items():
    L.append(f"  - {NAMES.get(s, s)}: median {c['median']:.4f}, range {c['lo']:.4f} to {c['hi']:.4f}")
(ROOT / "results" / "xs" / "ARMX_REPORT.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
